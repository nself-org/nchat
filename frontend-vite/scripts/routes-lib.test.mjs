/**
 * Purpose:    Guards the route generator: every page declares a unique route, the public
 *             allowlist has no stale entries, and the rendered table is well formed.
 * SOT:        F-NCHAT-VITE-ROUTES-01
 */
import { readdirSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { HOME_PATH, PUBLIC_PATHS, parsePages, renderRoutes } from './routes-lib.mjs'

const pagesDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'pages')
const realPages = readdirSync(pagesDir)
  .filter((f) => f.endsWith('Page.tsx'))
  .map((file) => ({ file, source: readFileSync(join(pagesDir, file), 'utf8') }))

const page = (file, path) => ({ file, source: `/** SOT: F-NCHAT-VITE-ROUTE — ${path} */` })

describe('routes generator', () => {
  const rows = parsePages(realPages)

  it('reads a route from every page and keeps them unique', () => {
    expect(rows).toHaveLength(realPages.length)
    expect(new Set(rows.map((r) => r.path)).size).toBe(rows.length)
    expect(rows.some((r) => r.path === HOME_PATH)).toBe(true)
  })

  it('has no stale entries in the public allowlist', () => {
    const paths = new Set(rows.map((r) => r.path))
    for (const p of PUBLIC_PATHS) expect(paths.has(p), `${p} has no page`).toBe(true)
  })

  it('renders a marked, complete table', () => {
    const out = renderRoutes(rows)
    expect(out).toContain('GENERATED BY scripts/generate-routes.mjs — DO NOT HAND EDIT')
    expect(out).toContain("export const HomePage = lazy(() => import('@/pages/HomePage'))")
    expect(out).toContain("{ path: '/login', Component: LoginPage },")
    const listed = out.match(/^ {2}\{ path: /gm) ?? []
    expect(listed).toHaveLength(rows.length - 1)
    const [pub, prot] = out.split('export const PROTECTED_ROUTES')
    expect(pub).toContain("path: '/login'")
    expect(prot).not.toContain("path: '/login'")
    expect(prot).toContain("path: '/chat'")
  })

  it('rejects a page without a route header', () => {
    expect(() => parsePages([{ file: 'XPage.tsx', source: '// nothing' }])).toThrow(/missing/)
  })

  it('rejects duplicate routes', () => {
    expect(() =>
      parsePages([page('HomePage.tsx', '/'), page('APage.tsx', '/a'), page('BPage.tsx', '/a')]),
    ).toThrow(/duplicate route \/a/)
  })

  it('requires a "/" page', () => {
    expect(() => parsePages([page('APage.tsx', '/a')])).toThrow(/"\/"/)
  })
})
