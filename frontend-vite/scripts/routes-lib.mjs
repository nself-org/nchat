/**
 * Purpose:    Pure helpers that turn the page files under src/pages into the react-router
 *             route table (src/routes.generated.tsx).
 * Inputs:     [{ file, source }] — page file names (e.g. "AdminUsersIdPage.tsx") + their text.
 *             Each page declares its URL in its header: `SOT: F-NCHAT-VITE-ROUTE — /admin/users/:id`.
 * Outputs:    parsePages() -> sorted [{ component, path }]; renderRoutes() -> TSX source text.
 * Constraints:No I/O, no side effects, so tests can call it directly. "/" is the HomePage entry,
 *             not a list row. PUBLIC_PATHS is the only auth decision; every other route is protected.
 * SOT:        F-NCHAT-VITE-ROUTES-01
 */

const ROUTE_RE = /F-NCHAT-VITE-ROUTE\s+—\s+(\S+)/

// Routes served without the RequireAuth gate (login, signup, /auth/*, invite, setup, offline,
// marketing/demo/docs). Everything else is nested under <RequireAuth> in App.tsx.
export const PUBLIC_PATHS = new Set([
  '/api-docs',
  '/api-docs/bots',
  '/auth/2fa-backup',
  '/auth/2fa-verify',
  '/auth/callback-complete',
  '/auth/forgot-password',
  '/auth/magic-link',
  '/auth/resend-verification',
  '/auth/reset-password',
  '/auth/signin',
  '/auth/signup',
  '/auth/verify-email',
  '/auth/verify-magic-link',
  '/demo',
  '/demo/animations',
  '/invite/:code',
  '/login',
  '/offline',
  '/search-demo',
  '/setup',
  '/setup/:step',
  '/signup',
  '/test-env',
])

export const HOME_PATH = '/'

/** Parse page files into { component, path } rows. Throws on a page with no route header. */
export function parsePages(pages) {
  const rows = pages.map(({ file, source }) => {
    const match = ROUTE_RE.exec(source)
    if (!match) throw new Error(`${file}: missing "SOT: F-NCHAT-VITE-ROUTE — <path>" header`)
    return { component: file.replace(/\.tsx$/, ''), path: match[1] }
  })
  const seen = new Map()
  for (const row of rows) {
    if (seen.has(row.path)) {
      throw new Error(`duplicate route ${row.path}: ${seen.get(row.path)} and ${row.component}`)
    }
    seen.set(row.path, row.component)
  }
  if (!seen.has(HOME_PATH)) throw new Error('no page declares the "/" route (HomePage)')
  return rows.sort((a, b) => a.component.localeCompare(b.component))
}

const row = ({ path, component }) => `  { path: '${path}', Component: ${component} },`

/** Render the full routes.generated.tsx text. */
export function renderRoutes(rows) {
  const home = rows.find((r) => r.path === HOME_PATH)
  const list = rows.filter((r) => r.path !== HOME_PATH)
  const lazyLine = ({ component }) => `const ${component} = lazy(() => import('@/pages/${component}'))`
  const byPath = (a, b) => a.path.localeCompare(b.path)
  const pub = list.filter((r) => PUBLIC_PATHS.has(r.path)).sort(byPath)
  const prot = list.filter((r) => !PUBLIC_PATHS.has(r.path)).sort(byPath)
  return `/**
 * GENERATED BY scripts/generate-routes.mjs — DO NOT HAND EDIT.
 * Purpose:    Route table for the ɳChat Vite SPA, one entry per src/pages/*Page.tsx
 *             (${rows.length} total), read from each page's "F-NCHAT-VITE-ROUTE" header.
 * Outputs:    PUBLIC_ROUTES + PROTECTED_ROUTES arrays + HomePage, consumed by App.tsx.
 * Constraints:Gitignored (*.generated.*); \`pnpm generate:routes\` rebuilds it and runs
 *             automatically before dev, build, type-check and test.
 *             Dynamic segments preserved: Next [id] -> :id, [...slug] -> *.
 * SOT:        F-NCHAT-VITE-ROUTES-01
 */
import { lazy, type LazyExoticComponent, type ComponentType } from 'react'

export interface RouteDef {
  path: string
  Component: LazyExoticComponent<ComponentType>
}

${list.map(lazyLine).join('\n')}
export const ${home.component} = lazy(() => import('@/pages/${home.component}'))

export const PUBLIC_ROUTES: RouteDef[] = [
${pub.map(row).join('\n')}
]

export const PROTECTED_ROUTES: RouteDef[] = [
${prot.map(row).join('\n')}
]
`
}
